#!/usr/bin/env python3
"""Voice the guided hot-spring soak cues in Erin's cloned voice, with the same guards as tools/voice_course.py
(one lock, skip clips already made, no retries, stop and write art/spring/voice/BLOCKED.json on the first provider
failure, which a later run refuses to pass; never delete it yourself). The cues are read from js/ext/world.js (the
SOAK_CUES list). js/spring/voice.js maps each exact cue to its clip. Run: python3 tools/voice_spring.py [--dry]"""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import voice_course as VC

ROOT = VC.ROOT
VC.OUT = ROOT / 'art' / 'spring' / 'voice'
VC.LOCK, VC.BLOCK, VC.LOG = VC.OUT / 'RUN.lock', VC.OUT / 'BLOCKED.json', VC.OUT / 'run.log'
VC.MANIFEST = ROOT / 'js' / 'spring' / 'voice.js'


def texts():
    src = (ROOT / 'js' / 'ext' / 'world.js').read_text()
    block = src.split('var SOAK_CUES = [', 1)[1].split('];', 1)[0]
    found = re.findall(r"\[\s*[0-9.]+\s*,\s*'((?:[^'\\]|\\.)*)'\s*\]", block)
    cue = [t.replace("\\'", "'") for t in found]
    return {'version': 'spring-1', 'texts': cue}


def write_manifest(data):
    clips = {}
    for t in data['texts']:
        f = VC.OUT / (VC.clip_id(t) + '.mp3')
        if f.exists():
            clips[t] = {'src': 'art/spring/voice/' + f.name, 'sec': VC.seconds(f)}
    VC.MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    VC.MANIFEST.write_text('/* Generated by tools/voice_spring.py: Erin\'s cloned voice for the guided soak cues. Keys are exact texts, so a\n'
                          ' * changed line has no clip until re-voiced. Do not edit by hand. */\n'
                          '(function (root) { root.EbbSpringVoice = ' + json.dumps({'voice': 'Erin', 'speed': VC.SPEED, 'clips': clips}, indent=1, ensure_ascii=False) +
                          '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
    return len(clips)


VC.texts = texts
VC.write_manifest = write_manifest
if __name__ == '__main__':
    VC.main()
