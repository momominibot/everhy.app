#!/usr/bin/env python3
"""Voice every course cue in Erin's cloned voice (Volcengine TTS, voice S_PLWb4DCd2, cluster volcano_icl), once.

Guarded like the art runner: one lock, skips clips already made, no retries, and stops the whole run on the first
provider failure (HTTP error, non-3000 code, empty or non-MP3 audio, timeout), writing art/course/voice/BLOCKED.json,
which a later run refuses to pass. Never delete that file yourself.

Clips are named by a hash of their exact caption text, and js/course/voice.js maps each current caption to its clip.
When a script changes after teacher review, the changed cue simply has no clip (captions only) until it is re-voiced,
so stale audio can never play under a new caption. The token is read from VOLC_TTS_TOKEN or ~/.hermes/.env and never
printed. Run: python3 tools/voice_course.py [--dry]"""
import base64, hashlib, json, os, subprocess, sys, time, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'art' / 'course' / 'voice'
LOCK, BLOCK, LOG = OUT / 'RUN.lock', OUT / 'BLOCKED.json', OUT / 'run.log'
MANIFEST = ROOT / 'js' / 'course' / 'voice.js'
URL = 'https://openspeech.bytedance.com/api/v1/tts'
APPID, VOICE, CLUSTER, SPEED = '9768801119', 'S_PLWb4DCd2', 'volcano_icl', 0.88

DUMP = """
const vm = require('vm'), fs = require('fs'), c = {}; c.globalThis = c; vm.createContext(c);
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), c);
const T = c.EbbCourseContent, P = T.PRACTICES, s = [];
for (const k in P) [P[k].cues, P[k].seated].filter(Boolean).forEach(cs => cs.forEach(x => { if (s.indexOf(x[1]) < 0) s.push(x[1]); }));
console.log(JSON.stringify({ version: T.VERSION, texts: s }));
"""


def texts():
    out = subprocess.run(['node', '-e', DUMP, str(ROOT / 'js/course/content.js')], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def clip_id(text):
    return hashlib.sha1(text.encode('utf-8')).hexdigest()[:12]


def token():
    t = os.environ.get('VOLC_TTS_TOKEN')
    if t:
        return t.strip()
    env = Path.home() / '.hermes' / '.env'
    for line in env.read_text().splitlines() if env.exists() else []:
        if line.startswith('VOLC_TTS_TOKEN='):
            return line.split('=', 1)[1].strip().strip('"\'')
    sys.exit('no VOLC_TTS_TOKEN found')


def log(msg):
    with open(LOG, 'a') as f:
        f.write(time.strftime('%H:%M:%S ') + msg + '\n')
    print(msg, flush=True)


def seconds(path):
    p = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(path)],
                       capture_output=True, text=True)
    try:
        return round(float(p.stdout.strip()), 2)
    except ValueError:
        return None


def speak(tok, text):
    body = json.dumps({
        'app': {'appid': APPID, 'token': tok, 'cluster': CLUSTER}, 'user': {'uid': 'ebb_course'},
        'audio': {'voice_type': VOICE, 'encoding': 'mp3', 'speed_ratio': SPEED},
        'request': {'reqid': 'ebb-' + clip_id(text) + '-' + str(int(time.time() * 1000)), 'text': text,
                    'text_type': 'plain', 'operation': 'query'}}).encode()
    req = urllib.request.Request(URL, data=body, method='POST',
                                 headers={'Authorization': 'Bearer; ' + tok, 'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=60) as r:
        status, raw = r.status, r.read()
    res = json.loads(raw)
    audio = base64.b64decode(res.get('data') or '')
    ok = status == 200 and res.get('code') == 3000 and len(audio) > 1000 and (audio[:3] == b'ID3' or audio[0] == 0xFF)
    return ok, audio, {'status': status, 'code': res.get('code'), 'message': str(res.get('message'))[:300]}


def write_manifest(data):
    clips = {}
    for t in data['texts']:
        f = OUT / (clip_id(t) + '.mp3')
        if f.exists():
            clips[t] = {'src': 'art/course/voice/' + f.name, 'sec': seconds(f)}
    MANIFEST.write_text('/* Generated by tools/voice_course.py: Erin\'s cloned voice (Volcengine ' + VOICE + ', speed ' +
                        str(SPEED) + ') for the course captions of script ' + data['version'] + '.\n * Keys are exact caption '
                        'texts, so a changed caption has no clip until re-voiced. Do not edit by hand. */\n'
                        '(function (root) { root.EbbCourseVoice = ' + json.dumps(
                            {'voice': 'Erin', 'speed': SPEED, 'scriptVersion': data['version'], 'clips': clips},
                            indent=1, ensure_ascii=False) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
    return len(clips)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    data = texts()
    if '--dry' in sys.argv:
        todo = [t for t in data['texts'] if not (OUT / (clip_id(t) + '.mp3')).exists()]
        print(f"{len(data['texts'])} captions, {len(todo)} to voice, {sum(len(t) for t in todo)} characters")
        return
    if BLOCK.exists():
        sys.exit('BLOCKED: ' + BLOCK.read_text())
    try:
        fd = os.open(LOCK, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        sys.exit('another run holds the lock')
    os.write(fd, str(os.getpid()).encode()); os.close(fd)
    try:
        tok = token()
        for t in data['texts']:
            out = OUT / (clip_id(t) + '.mp3')
            if out.exists():
                continue
            t0 = time.time()
            try:
                ok, audio, info = speak(tok, t)
            except Exception as e:  # network, timeout, HTTP error, bad JSON: all stop the run
                ok, audio, info = False, b'', {'error': type(e).__name__ + ': ' + str(e)[:300]}
            if ok:
                out.write_bytes(audio)
                sec = seconds(out)
                ok = bool(sec and sec > 0.5)
                if not ok:
                    out.rename(out.with_suffix('.suspect.mp3'))
                    info['error'] = 'audio did not decode'
            log(f"{out.name} {time.time() - t0:.1f}s ok={ok} {info.get('code', '')}")
            if not ok:
                BLOCK.write_text(json.dumps({'clip': out.name, 'text': t[:80], **info, 'at': time.ctime()}, indent=1))
                sys.exit('stopped; see ' + str(BLOCK))
        log('voice run complete')
    finally:
        LOCK.unlink(missing_ok=True)
        log(f'manifest: {write_manifest(data)} clips')


if __name__ == '__main__':
    main()
