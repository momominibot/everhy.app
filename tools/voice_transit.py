#!/usr/bin/env python3
"""Voice the short seat practices on the MRT and the bus in Erin's cloned voice, with the same guards as
tools/voice_course.py (one lock, skip clips already made, no retries, stop and write art/transit/voice/BLOCKED.json
on the first provider failure, which a later run refuses to pass; never delete it yourself). Lines: the five
"Notice five things" cues and the two counted-breath cues ("Breathe in", "Breathe out"), read from
js/transit/rules.js. js/transit/voice.js maps each exact line to its clip. Run: python3 tools/voice_transit.py [--dry]"""
import json, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import voice_course as VC

ROOT = VC.ROOT
VC.OUT = ROOT / 'art' / 'transit' / 'voice'
VC.LOCK, VC.BLOCK, VC.LOG = VC.OUT / 'RUN.lock', VC.OUT / 'BLOCKED.json', VC.OUT / 'run.log'
VC.MANIFEST = ROOT / 'js' / 'transit' / 'voice.js'

DUMP = """
const vm = require('vm'), fs = require('fs'), c = {}; c.globalThis = c; vm.createContext(c);
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), c);
const R = c.EbbTransitRules, s = [], add = t => { if (t && s.indexOf(t) < 0) s.push(t); };
R.NOTICE.forEach(add);
R.BREATH.forEach(b => add(b[0]));
console.log(JSON.stringify({ version: R.VERSION, texts: s }));
"""


def texts():
    out = subprocess.run(['node', '-e', DUMP, str(ROOT / 'js' / 'transit' / 'rules.js')], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def write_manifest(data):
    clips = {}
    for t in data['texts']:
        f = VC.OUT / (VC.clip_id(t) + '.mp3')
        if f.exists():
            clips[t] = {'src': 'art/transit/voice/' + f.name, 'sec': VC.seconds(f)}
    VC.MANIFEST.write_text('/* Generated by tools/voice_transit.py: Erin\'s cloned voice for the MRT and bus seat practices. Keys are exact\n'
                           ' * texts, so a changed line has no clip until re-voiced. Do not edit by hand. */\n'
                           '(function (root) { root.EbbTransitVoice = ' + json.dumps({'voice': 'Erin', 'speed': VC.SPEED, 'clips': clips}, indent=1, ensure_ascii=False) +
                           '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
    return len(clips)


VC.texts = texts
VC.write_manifest = write_manifest
if __name__ == '__main__':
    VC.main()
