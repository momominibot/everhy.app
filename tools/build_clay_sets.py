#!/usr/bin/env python3
"""Write js/ebb-clay-sets.js from the strip metadata in art/chars/<set>/*.json and art/props/*.json, so the game knows each outfit's
frames without fetching anything. A set is usable when it has idle, walk_front, walk_back, walk_side, sit and work."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NEED = ['idle', 'walk_front', 'walk_back', 'walk_side', 'sit', 'work']
sets = {}
for d in sorted((ROOT / 'art/chars').iterdir()):
    if not d.is_dir():
        continue
    strips = {j.stem: {k: v for k, v in json.loads(j.read_text()).items() if k in ('frames', 'w', 'h')} for j in d.glob('*.json')}
    if all(n in strips for n in NEED):
        sets[d.name] = strips
out = ('/* generated by tools/build_clay_sets.py: clay sprite strips per outfit, {frames, w, h} in pixels */\n'
       '(function (root) { root.EbbClaySets = ' + json.dumps(sets, sort_keys=True) + '; })'
       "(typeof window !== 'undefined' ? window : globalThis);\n")
props = {}
for d in ('props', 'furn', 'ui'):  # every strip folder, each entry remembering its folder
    for j in sorted((ROOT / 'art' / d).glob('*.json')) if (ROOT / 'art' / d).exists() else []:
        m = json.loads(j.read_text()); props[j.stem] = {k: m[k] for k in ('frames', 'w', 'h', 'boxes') if k in m}; props[j.stem]['dir'] = d
out += ('/* clay prop strips in art/props, art/furn and art/ui: {frames, w, h, boxes, dir} */\n(function (root) { root.EbbPropSprites = ' + json.dumps(props, sort_keys=True) + '; })'
        "(typeof window !== 'undefined' ? window : globalThis);\n")
(ROOT / 'js/ebb-clay-sets.js').write_text(out)
print('props', sorted(props))
print({k: sorted(v) for k, v in sets.items()})
