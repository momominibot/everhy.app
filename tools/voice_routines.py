#!/usr/bin/env python3
"""Voice the routine lines in Erin's cloned voice, with exactly the same guards as tools/voice_course.py (one lock, skip
clips already made, no retries, stop and write art/routines/voice/BLOCKED.json on the first provider failure, which a
later run refuses to pass; never delete it yourself). Lines: each routine's prompt (fresh and resume), every step cue,
and each routine's closing line, read from js/routines/rules.js. js/routines/voice.js maps each exact line to its clip.
Run: python3 tools/voice_routines.py [--dry]"""
import json, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import voice_course as VC

ROOT = VC.ROOT
VC.OUT = ROOT / 'art' / 'routines' / 'voice'
VC.LOCK, VC.BLOCK, VC.LOG = VC.OUT / 'RUN.lock', VC.OUT / 'BLOCKED.json', VC.OUT / 'run.log'
VC.MANIFEST = ROOT / 'js' / 'routines' / 'voice.js'

DUMP = """
const vm = require('vm'), fs = require('fs'), c = {}; c.globalThis = c; vm.createContext(c);
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), c);
const K = c.EbbRoutineRules, s = [], add = t => { if (t && s.indexOf(t) < 0) s.push(t); };
Object.keys(K.ROUTINES).forEach(r => { add(K.promptLine(r, false)); add(K.promptLine(r, true)); add(K.ROUTINES[r].done); });
Object.keys(K.CATALOG).forEach(k => (K.CATALOG[k].cues || []).forEach(x => add(x[1])));
console.log(JSON.stringify({ version: 'routines-1', texts: s }));
"""


def texts():
    out = subprocess.run(['node', '-e', DUMP, str(ROOT / 'js/routines/rules.js')], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def write_manifest(data):
    clips = {}
    for t in data['texts']:
        f = VC.OUT / (VC.clip_id(t) + '.mp3')
        if f.exists():
            clips[t] = {'src': 'art/routines/voice/' + f.name, 'sec': VC.seconds(f)}
    VC.MANIFEST.write_text('/* Generated by tools/voice_routines.py: Erin\'s cloned voice for the routine lines. Keys are exact texts, so a\n'
                           ' * changed line has no clip until re-voiced. Do not edit by hand. */\n'
                           '(function (root) { root.EbbRoutineVoice = ' + json.dumps({'voice': 'Erin', 'speed': VC.SPEED, 'clips': clips}, indent=1, ensure_ascii=False) +
                           '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
    return len(clips)


VC.texts = texts
VC.write_manifest = write_manifest
if __name__ == '__main__':
    VC.main()
