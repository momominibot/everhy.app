#!/usr/bin/env python3
"""Voice the meditation library cues in Erin's cloned voice, with exactly the same guards as tools/voice_course.py
(one lock, skip clips already made, no retries, stop and write art/meditate/voice/BLOCKED.json on the first provider
failure, which a later run refuses to pass; never delete it yourself). Lines: every practice cue, read from
js/meditate/rules.js. js/meditate/voice.js maps each exact line to its clip.
Run: python3 tools/voice_meditate.py [--dry]"""
import json, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import voice_course as VC

ROOT = VC.ROOT
VC.OUT = ROOT / 'art' / 'meditate' / 'voice'
VC.LOCK, VC.BLOCK, VC.LOG = VC.OUT / 'RUN.lock', VC.OUT / 'BLOCKED.json', VC.OUT / 'run.log'
VC.MANIFEST = ROOT / 'js' / 'meditate' / 'voice.js'

DUMP = """
const vm = require('vm'), fs = require('fs'), c = {}; c.globalThis = c; vm.createContext(c);
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), c);
const K = c.EbbMeditateRules, s = [];
Object.keys(K.PRACTICES).forEach(k => K.PRACTICES[k].cues.forEach(x => { if (s.indexOf(x[1]) < 0) s.push(x[1]); }));
console.log(JSON.stringify({ version: K.VERSION, texts: s }));
"""


def texts():
    out = subprocess.run(['node', '-e', DUMP, str(ROOT / 'js/meditate/rules.js')], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def write_manifest(data):
    clips = {}
    for t in data['texts']:
        f = VC.OUT / (VC.clip_id(t) + '.mp3')
        if f.exists():
            clips[t] = {'src': 'art/meditate/voice/' + f.name, 'sec': VC.seconds(f)}
    VC.MANIFEST.write_text('/* Generated by tools/voice_meditate.py: Erin\'s cloned voice for the meditation cues. Keys are exact\n'
                           ' * texts, so a changed line has no clip until re-voiced. Do not edit by hand. */\n'
                           '(function (root) { root.EbbMeditateVoice = ' + json.dumps({'voice': 'Erin', 'speed': VC.SPEED, 'clips': clips}, indent=1, ensure_ascii=False) +
                           '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
    return len(clips)


VC.texts = texts
VC.write_manifest = write_manifest
if __name__ == '__main__':
    VC.main()
